def _run(
    run_id: int,
    model_type: str,
    metrics: dict,
    dataset: str = "diabetes.csv",
    target: str = "Outcome",
    exp_type: str = "classification",
    test_size: float = 0.2,
    random_state: int = 42,
    extra_config: dict = None,
    created_at: str = "2026-11-12T00:00:00",
):
    cfg = {
        "model_type": model_type,
        "test_size": test_size,
        "random_state": random_state,
        "params": {},
    }
    if target is not None:
        cfg["target_column"] = target
    if extra_config:
        cfg.update(extra_config)
    return {
        "id": run_id,
        "workspace_id": 4,
        "dataset_name": dataset,
        "experiment_type": exp_type,
        "config": cfg,
        "metrics": metrics,
        "created_at": created_at,
    }


def test_find_comparable_runs_filters_strictly_on_all_five_criteria():
    rf_base = _run(5, "Random Forest", {"accuracy": 0.7597})
    lr_match = _run(6, "Logistic Regression", {"accuracy": 0.7143})
    lr_diff_dataset = _run(7, "Logistic Regression", {"accuracy": 0.9}, dataset="iris.csv")
    lr_diff_target = _run(8, "Logistic Regression", {"accuracy": 0.8}, target="Age")
    lr_diff_type = _run(9, "Random Forest Regressor", {"r2_score": 0.5}, exp_type="regression")
    lr_diff_split = _run(10, "Logistic Regression", {"accuracy": 0.72}, test_size=0.3)
    lr_diff_seed = _run(11, "Logistic Regression", {"accuracy": 0.73}, random_state=7)

    res = analysis_service.find_comparable_runs(
        rf_base,
        workspace_runs=[rf_base, lr_match, lr_diff_dataset, lr_diff_target, lr_diff_type, lr_diff_split, lr_diff_seed],
    )
    comparable_ids = [r["id"] for r in res["comparable_runs"]]
    assert comparable_ids == [5, 6]
    assert len(res["non_comparable_runs"]) == 5


def test_comparative_analysis_supported_and_percentage_point_diffs():
    rf = _run(
        5,
        "Random Forest",
        {"accuracy": 0.7597, "precision_weighted": 0.7546, "recall_weighted": 0.7597, "f1_weighted": 0.7555},
        target=None,
    )
    lr = _run(
        6,
        "Logistic Regression",
        {"accuracy": 0.7143, "precision_weighted": 0.7065, "recall_weighted": 0.7143, "f1_weighted": 0.7084},
        target=None,
    )

    with patch.object(analysis_service, "is_llm_configured", return_value=(False, "Ollama stopped")):
        out = analysis_service.analyze_and_interpret_run(
            {"id": 4, "research_question": "Does RF beat LR?", "hypothesis": "RF > LR"},
            rf,
            workspace_runs=[rf, lr],
        )

    interp = out["interpretation"]
    comp = out["comparison"]
    assert comp["comparison_available"] is True
    assert comp["hypothesis_status"] == "Supported"
    assert interp["hypothesis_status"] == "Supported"
    assert out["analysis_mode"] == "comparative_rule_based"
    assert interp["source_label"] == "Rule-Based Interpretation — Not Generated by Gemini"

    acc_row = next(r for r in comp["metrics_table"] if r["metric_key"] == "accuracy")
    assert acc_row["signed_diff_pp"] == pytest.approx(4.54, abs=1e-2)
    assert acc_row["abs_diff_pp"] == pytest.approx(4.54, abs=1e-2)
    assert acc_row["winner"] == "Random Forest"

    # Weighted averages only -> must NOT infer class-level performance
    assert comp["class_level_comparison"]["available"] is False
    assert "cannot be inferred from weighted averages" in comp["class_level_comparison"]["note"].lower()


def test_comparative_analysis_not_supported_when_logistic_regression_better():
    rf = _run(2, "Random Forest", {"accuracy": 0.9000, "f1_weighted": 0.8997}, dataset="iris")
    lr = _run(1, "Logistic Regression", {"accuracy": 0.9333, "f1_weighted": 0.9333}, dataset="iris")

    comp = analysis_service.build_comparative_analysis(rf, workspace_runs=[rf, lr])
    assert comp["hypothesis_status"] == "Not Supported"
    acc_row = next(r for r in comp["metrics_table"] if r["metric_key"] == "accuracy")
    assert acc_row["signed_diff_pp"] == pytest.approx(-3.33, abs=1e-2)
    assert acc_row["abs_diff_pp"] == pytest.approx(3.33, abs=1e-2)
    assert acc_row["winner"] == "Logistic Regression"


def test_comparative_analysis_inconclusive_for_tied_incomplete_and_non_comparable():
    rf = _run(1, "Random Forest", {"accuracy": 0.8000, "f1_weighted": 0.8000})
    lr_tie = _run(2, "Logistic Regression", {"accuracy": 0.8000, "f1_weighted": 0.8000})
    comp_tie = analysis_service.build_comparative_analysis(rf, workspace_runs=[rf, lr_tie])
    assert comp_tie["hypothesis_status"] == "Inconclusive"
    assert comp_tie["comparison_status"] == "tied"

    # Incomplete (no counterpart run) -> Inconclusive even via analyze_and_interpret_run
    comp_incomplete = analysis_service.build_comparative_analysis(rf, workspace_runs=[rf])
    assert comp_incomplete["comparison_available"] is False
    assert comp_incomplete["hypothesis_status"] == "Inconclusive"
    assert comp_incomplete["comparison_status"] == "incomplete"

    rf_high = _run(9, "Random Forest", {"accuracy": 0.9500, "f1_weighted": 0.9500})
    comp_ws = {"id": 4, "research_question": "Does Random Forest outperform Logistic Regression?", "hypothesis": "RF > LR"}
    with patch.object(analysis_service, "is_llm_configured", return_value=(False, "Ollama stopped")):
        inc_out = analysis_service.analyze_and_interpret_run(comp_ws, rf_high, workspace_runs=[rf_high])
    assert inc_out["interpretation"]["hypothesis_status"] == "Inconclusive"
    assert any("Logistic Regression" in r["title"] for r in inc_out["recommendations"])

    # Not comparable (different random seed)
    lr_diff_seed = _run(3, "Logistic Regression", {"accuracy": 0.7000}, random_state=99)
    comp_mismatch = analysis_service.build_comparative_analysis(rf, workspace_runs=[rf, lr_diff_seed])
    assert comp_mismatch["comparison_available"] is False
    assert comp_mismatch["hypothesis_status"] == "Inconclusive"
    assert comp_mismatch["comparison_status"] == "not_comparable"

    # Selected evaluation metrics: RF leads accuracy (+2pp), LR leads recall (+2pp) -> mixed/inconclusive together, decisive individually
    rf_mixed = _run(4, "Random Forest", {"accuracy": 0.82, "recall_weighted": 0.78})
    lr_mixed = _run(5, "Logistic Regression", {"accuracy": 0.80, "recall_weighted": 0.80})
    assert analysis_service.build_comparative_analysis(rf_mixed, [rf_mixed, lr_mixed], selected_metrics=["accuracy"])["hypothesis_status"] == "Supported"
    assert analysis_service.build_comparative_analysis(rf_mixed, [rf_mixed, lr_mixed], selected_metrics=["recall_weighted"])["hypothesis_status"] == "Not Supported"
    assert analysis_service.build_comparative_analysis(rf_mixed, [rf_mixed, lr_mixed])["hypothesis_status"] == "Inconclusive"


def test_class_specific_metrics_and_confusion_matrix_comparison():
    rf = _run(
        1,
        "Random Forest",
        {
            "accuracy": 0.85,
            "confusion_matrix": [[45, 5], [10, 40]],
            "classes": ["Negative", "Positive"],
        },
    )
    lr = _run(
        2,
        "Logistic Regression",
        {
            "accuracy": 0.80,
            "confusion_matrix": [[44, 6], [14, 36]],
            "classes": ["Negative", "Positive"],
        },
    )

    comp = analysis_service.build_comparative_analysis(rf, workspace_runs=[rf, lr])
    cls_comp = comp["class_level_comparison"]
    assert cls_comp["available"] is True
    assert cls_comp["rf_confusion_matrix"] == [[45, 5], [10, 40]]
    assert cls_comp["lr_confusion_matrix"] == [[44, 6], [14, 36]]
    pos_row = next(r for r in cls_comp["per_class_rows"] if r["class"] == "Positive")
    # RF Positive recall = 40/50 = 0.80; LR Positive recall = 36/50 = 0.72 -> |diff| = 8.0 pp
    assert pos_row["rf_recall"] == pytest.approx(0.80, abs=1e-4)
    assert pos_row["lr_recall"] == pytest.approx(0.72, abs=1e-4)
    assert pos_row["recall_abs_diff_pp"] == pytest.approx(8.0, abs=1e-2)


def test_duplicate_recommendation_prevention_and_meaningful_alternatives():
    rf = _run(5, "Random Forest", {"accuracy": 0.7597, "f1_weighted": 0.7555})
    lr = _run(6, "Logistic Regression", {"accuracy": 0.7143, "f1_weighted": 0.7084})
    rf_sweep_n = _run(
        7,
        "Random Forest",
        {"sweep_steps": 5},
        exp_type="parameter_sweep",
        extra_config={"param_name": "n_estimators", "param_values": [10, 25, 50, 100, 200]},
    )

    with patch.object(analysis_service, "is_llm_configured", return_value=(False, "Ollama stopped")):
        out = analysis_service.analyze_and_interpret_run(
            {"id": 4, "research_question": "RF vs LR?", "hypothesis": "RF > LR"},
            rf,
            workspace_runs=[rf, lr, rf_sweep_n],
        )

    rec_titles = [r["title"] for r in out["recommendations"]]
    # Must NOT recommend repeating Logistic Regression vs Random Forest comparison
    assert not any("baseline" in t.lower() or "contrast" in t.lower() for t in rec_titles)
    # Must NOT repeat n_estimators sweep since already done; should tune max_depth instead
    assert not any("n_estimators" in t.lower() for t in rec_titles)
    assert any("C Hyperparameter Sweep" in t for t in rec_titles)
    assert any("max_depth" in t for t in rec_titles)
    assert any("Stratified" in t for t in rec_titles)
    assert any("Recall" in t and "False-Negative" in t for t in rec_titles)
    assert any("Random Seeds" in t for t in rec_titles)


def test_sqlite_history_retrieval_and_gemini_vs_rule_based_distinction():
    temp_dir = tempfile.mkdtemp()
    orig_config_db = core.config.DB_PATH
    orig_db_module_db = database.DB_PATH
    try:
        test_db = Path(temp_dir) / "comp_test.db"
        core.config.DB_PATH = test_db
        database.DB_PATH = test_db
        database.init_db()

        ws_id = database.create_workspace(
            title="Diabetes Benchmark",
            research_question="Does RF beat LR on diabetes.csv?",
            hypothesis="Random Forest achieves higher accuracy than Logistic Regression.",
        )
        # Legacy-style SQLite rows without target_column in config
        rf_id = database.save_experiment_run(
            workspace_id=ws_id,
            dataset_name="diabetes.csv",
            experiment_type="classification",
            config_dict={"model_type": "Random Forest", "test_size": 0.2, "random_state": 42, "params": {}},
            metrics_dict={"accuracy": 0.7597, "precision_weighted": 0.7546, "recall_weighted": 0.7597, "f1_weighted": 0.7555},
        )
        database.save_experiment_run(
            workspace_id=ws_id,
            dataset_name="diabetes.csv",
            experiment_type="classification",
            config_dict={"model_type": "Logistic Regression", "test_size": 0.2, "random_state": 42, "params": {}},
            metrics_dict={"accuracy": 0.7143, "precision_weighted": 0.7065, "recall_weighted": 0.7143, "f1_weighted": 0.7084},
        )

        ws = database.get_workspace(ws_id)
        rf_run = database.get_experiment_run(rf_id)

        # 1. Quota exhausted -> comparative rule-based fallback reading runs from SQLite automatically
        quota_err = llm_service.GeminiQuotaExhaustedError("Daily quota exhausted", retry_after="20s")
        with (
            patch.object(analysis_service, "is_gemini_configured", return_value=(True, "Configured")),
            patch.object(analysis_service, "interpret_results_llm", side_effect=quota_err),
        ):
            rb_out = analysis_service.analyze_and_interpret_run(ws, rf_run, provider="gemini")

        assert rb_out["source"] == "rule_based"
        assert rb_out["analysis_mode"] == "comparative_rule_based"
        assert rb_out["interpretation"]["hypothesis_status"] == "Supported"
        assert rb_out["comparison"]["rf_run_id"] == rf_id

        # 2. Gemini active -> comparative Gemini interpretation + redundant rec filtered out
        mock_interp = InterpretationResult(
            summary="Gemini compared RF (75.97%) vs LR (71.43%).",
            what_results_suggest="RF outperformed LR by 4.54 percentage points.",
            hypothesis_status="Supported",
            possible_reasons=["Nonlinear interactions captured by tree ensemble."],
            limitations=["Single 80/20 split without cross-validation."],
        )
        redundant_llm_recs = [
            NextExperimentRecommendation(
                title="Compare Logistic Regression vs Random Forest",
                what_to_change="Switch between Logistic Regression and Random Forest",
                what_to_keep_constant="Same split",
                what_to_measure="Accuracy",
                why_useful="Redundant check",
                expected_support_or_weakening="Check diff",
                can_run_predefined=True,
                recommended_runner_config={"experiment_type": "Classification", "model_choice": "Logistic Regression"},
            ),
            NextExperimentRecommendation(
                title="Logistic Regression C Hyperparameter Sweep",
                what_to_change="Sweep C across [0.01, 0.1, 1.0, 10.0]",
                what_to_keep_constant="Same split and seed",
                what_to_measure="F1-weighted",
                why_useful="Tune regularization",
                expected_support_or_weakening="Higher F1 narrows gap",
                can_run_predefined=True,
                recommended_runner_config={"experiment_type": "Parameter Sweep", "model_choice": "Logistic Regression", "sweep_param": "C"},
            ),
        ]
        with (
            patch.object(analysis_service, "is_gemini_configured", return_value=(True, "Configured")),
            patch.object(analysis_service, "interpret_results_llm", return_value=mock_interp),
            patch.object(analysis_service, "retrieve_relevant_chunks", return_value=[]),
            patch.object(analysis_service, "recommend_next_experiments_llm", return_value=redundant_llm_recs),
        ):
            gem_out = analysis_service.analyze_and_interpret_run(ws, rf_run, provider="gemini")

        assert gem_out["source"] == "gemini"
        assert gem_out["analysis_mode"] == "comparative_gemini"
        assert gem_out["interpretation"]["source_label"] == "AI-Generated Interpretation (Gemini)"
        # Redundant comparison was filtered out, keeping only non-redundant C sweep
        assert len(gem_out["recommendations"]) == 1
        assert gem_out["recommendations"][0]["title"] == "Logistic Regression C Hyperparameter Sweep"
    finally:
        core.config.DB_PATH = orig_config_db
        database.DB_PATH = orig_db_module_db
