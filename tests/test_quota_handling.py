def test_preserves_run_data_and_recovers_when_quota_returns():
    temp_dir = tempfile.mkdtemp()
    from core import database
    orig_config_db = core.config.DB_PATH
    orig_db_module_db = database.DB_PATH
    try:
        test_db = Path(temp_dir) / "quota_test.db"
        core.config.DB_PATH = test_db
        database.DB_PATH = test_db
        database.init_db()

        ws_id = database.create_workspace(
            title="Quota Recovery Workspace",
            research_question="Can RF classify Iris?",
            hypothesis="RF > 90% accuracy",
        )
        original_config = {"model_type": "Random Forest", "test_size": 0.2, "random_state": 42}
        original_metrics = {"accuracy": 0.9667, "precision_weighted": 0.9697, "recall_weighted": 0.9667, "f1_weighted": 0.9666}
        run_id = database.save_experiment_run(
            workspace_id=ws_id,
            dataset_name="iris",
            experiment_type="classification",
            config_dict=original_config,
            metrics_dict=original_metrics,
        )
        ws = database.get_workspace(ws_id)
        run_rec = database.get_experiment_run(run_id)

        # 1. Quota exhausted -> save rule-based fallback, verify metrics & config preserved
        quota_err = llm_service.GeminiQuotaExhaustedError("Daily quota exhausted", retry_after="30s")
        with (
            patch.object(analysis_service, "is_gemini_configured", return_value=(True, "Configured")),
            patch.object(analysis_service, "interpret_results_llm", side_effect=quota_err),
        ):
            fallback_out = analysis_service.analyze_and_interpret_run(ws, run_rec)

        database.update_run_interpretation(
            run_id,
            json.dumps(fallback_out["interpretation"]),
            json.dumps(fallback_out["recommendations"]),
        )
        saved_after_fallback = database.get_experiment_run(run_id)
        assert saved_after_fallback["metrics"] == original_metrics
        assert saved_after_fallback["config"] == original_config
        assert json.loads(saved_after_fallback["interpretation"])["source_label"] == "Rule-Based Interpretation — Not Generated by Gemini"

        # 2. Quota recovers -> Gemini interpretation works again
        mock_interp = InterpretationResult(
            summary="Gemini observed 96.67% accuracy on Iris.",
            what_results_suggest="Strong separation across species.",
            hypothesis_status="Supported",
            possible_reasons=["Non-linear splits capture petal geometry."],
            limitations=["Small sample size (n=150)."],
        )
        mock_recs = [
            NextExperimentRecommendation(
                title="Tree Count Sweep",
                what_to_change="Vary n_estimators",
                what_to_keep_constant="Seed 42, 80/20 split",
                what_to_measure="Weighted F1",
                why_useful="Check stability",
                expected_support_or_weakening="Stable F1 >= 0.95 supports robustness",
                can_run_predefined=True,
            )
        ]
        with (
            patch.object(analysis_service, "is_gemini_configured", return_value=(True, "Configured")),
            patch.object(analysis_service, "interpret_results_llm", return_value=mock_interp),
            patch.object(analysis_service, "retrieve_relevant_chunks", return_value=[]),
            patch.object(analysis_service, "recommend_next_experiments_llm", return_value=mock_recs),
        ):
            recovered_out = analysis_service.analyze_and_interpret_run(ws, saved_after_fallback)

        assert recovered_out["quota_exhausted"] is False
        assert recovered_out["source"] == "gemini"
        assert recovered_out["interpretation"]["source"] == "gemini"
        assert recovered_out["interpretation"]["source_label"] == "AI-Generated Interpretation (Gemini)"
    finally:
        core.config.DB_PATH = orig_config_db
        database.DB_PATH = orig_db_module_db


