def _make_daily_quota_error(retry_delay: str = "25s", with_retry_info: bool = True) -> errors.ClientError:
    details = [
        {
            "@type": "type.googleapis.com/google.rpc.QuotaFailure",
            "violations": [
                {
                    "quotaMetric": "generativelanguage.googleapis.com/generate_content_free_tier_requests",
                    "quotaId": "GenerateRequestsPerDayPerProjectPerModel-FreeTier",
                    "quotaValue": "20",
                }
            ],
        }
    ]
    msg = "You exceeded your current quota, please check your plan and billing details."
    if with_retry_info:
        details.append({"@type": "type.googleapis.com/google.rpc.RetryInfo", "retryDelay": retry_delay})
        msg += f" Please retry in {retry_delay}."

    payload = {
        "error": {
            "code": 429,
            "message": msg,
            "status": "RESOURCE_EXHAUSTED",
            "details": details,
        }
    }
    return errors.ClientError(429, payload)


def test_daily_quota_429_is_detected_and_not_retried():
    err = _make_daily_quota_error(retry_delay="14.371248s", with_retry_info=True)
    mock_client = MagicMock()
    mock_client.models.generate_content.side_effect = err

    with (
        patch.object(llm_service, "is_gemini_configured", return_value=(True, "Configured")),
        patch.object(llm_service, "get_gemini_client", return_value=mock_client),
        patch.object(llm_service.time, "sleep") as mock_sleep,
    ):
        with pytest.raises(llm_service.GeminiQuotaExhaustedError) as exc_info:
            llm_service.call_gemini_with_retry("test prompt", system_instruction="system", max_retries=2)

    # Must not retry 3 times — called once and no sleep backoff
    assert mock_client.models.generate_content.call_count == 1
    assert mock_sleep.call_count == 0
    assert exc_info.value.is_daily_quota is True
    assert exc_info.value.retry_after == "14.4s"
    assert "daily quota has been exhausted" in str(exc_info.value).lower()
    assert "14.4s" in str(exc_info.value)


