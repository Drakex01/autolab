def test_analysis_falls_back_to_labeled_rule_based_on_quota_exhausted():
    workspace = {
        "id": 101,
        "research_question": "Does Random Forest classify Iris accurately?",
        "hypothesis": "Random Forest achieves high classification accuracy.",
    }
    run_record = {
        "id": 7,
        "experiment_type": "classification",
        "config": {"model_type": "Random Forest", "test_size": 0.2, "random_state": 42},
        "metrics": {
            "accuracy": 0.9667,
            "precision_weighted": 0.9697,
            "recall_weighted": 0.9667,
            "f1_weighted": 0.9666,
        },
    }

    quota_err = llm_service.GeminiQuotaExhaustedError(
        "Gemini API daily quota has been exhausted (HTTP 429 RESOURCE_EXHAUSTED). Please retry in 25s.",
        retry_after="25s",
        is_daily_quota=True,
    )

    with (
        patch.object(analysis_service, "is_gemini_configured", return_value=(True, "Configured")),
        patch.object(analysis_service, "interpret_results_llm", side_effect=quota_err),
    ):
        out = analysis_service.analyze_and_interpret_run(workspace, run_record)

    interp = out["interpretation"]
    assert out["quota_exhausted"] is True
    assert out["retry_after"] == "25s"
    assert out["source"] == "rule_based"
    assert interp["source"] == "rule_based"
    assert interp["source_label"] == "Rule-Based Interpretation — Not Generated by Gemini"
    assert interp["fallback_reason"] == "quota_exhausted"
    assert interp["retry_after"] == "25s"
    assert interp["hypothesis_status"] == "Supported"
    # Grounded strictly in real metrics
    assert "96.67%" in interp["summary"]
    assert "0.9666" in interp["summary"]
    assert len(out["recommendations"]) >= 1


