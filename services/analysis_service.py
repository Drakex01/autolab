from typing import Dict, Any, List, Optional, Tuple
from core.schemas import InterpretationResult, NextExperimentRecommendation
from services.llm_service import (
    GeminiQuotaExhaustedError,
    is_gemini_configured,
    interpret_results_llm,
    recommend_next_experiments_llm,
)
from services.retrieval_service import retrieve_relevant_chunks

RULE_BASED_LABEL = "Rule-Based Interpretation — Not Generated by Gemini"
GEMINI_LABEL = "AI-Generated Interpretation (Gemini)"


def _build_rule_based_parts(
    exp_type: str,
    model_name: str,
    config: Dict[str, Any],
    metrics: Dict[str, Any],
) -> Tuple[InterpretationResult, List[NextExperimentRecommendation]]:
    """Builds a deterministic interpretation and follow-up suggestions strictly from real metrics/config."""
    test_size = config.get("test_size")
    random_state = config.get("random_state")
    split_note = (
        f" on a {int((1 - test_size) * 100)}/{int(test_size * 100)} train/test split (seed {random_state})"
        if isinstance(test_size, (int, float)) and random_state is not None
        else ""
    )

    if exp_type == "classification":
        acc = metrics.get("accuracy")
        prec = metrics.get("precision_weighted")
        rec = metrics.get("recall_weighted")
        f1 = metrics.get("f1_weighted")

        if isinstance(acc, (int, float)):
            if acc >= 0.85:
                status = "Supported"
                level = "strong"
            elif acc >= 0.60:
                status = "Inconclusive"
                level = "moderate"
            else:
                status = "Not Supported"
                level = "weak"
            acc_pct = f"{acc * 100:.2f}%"
        else:
            status = "Inconclusive"
            level = "unverified"
            acc_pct = "N/A"

        f1_str = f"{f1:.4f}" if isinstance(f1, (int, float)) else "N/A"
        prec_str = f"{prec:.4f}" if isinstance(prec, (int, float)) else "N/A"
        rec_str = f"{rec:.4f}" if isinstance(rec, (int, float)) else "N/A"

        summary = (
            f"The {model_name} classifier achieved a test accuracy of {acc_pct}, "
            f"weighted F1-score of {f1_str}, precision of {prec_str}, and recall of {rec_str}{split_note}."
        )
        what_suggests = (
            f"Observed test accuracy ({acc_pct}) and weighted F1 ({f1_str}) indicate {level} class "
            f"separability on the held-out evaluation split."
        )

        reasons = [
            f"Measured precision ({prec_str}) and recall ({rec_str}) reflect the classifier's performance after standard scaling and imputation{split_note}."
        ]
        if isinstance(prec, (int, float)) and isinstance(rec, (int, float)):
            gap = abs(prec - rec)
            if gap < 0.05:
                reasons.append(f"Precision and recall are closely balanced (gap = {gap:.4f}), indicating consistent predictions across classes.")
            else:
                reasons.append(f"Precision and recall diverge by {gap:.4f}, suggesting class-level trade-offs or class imbalance.")

        sweep_param = "n_estimators" if "Random Forest" in model_name else "C"
        alt_model = "Logistic Regression" if "Random Forest" in model_name else "Random Forest"
        recs = [
            NextExperimentRecommendation(
                title=f"{model_name} Hyperparameter Sweep ({sweep_param})",
                what_to_change=f"Sweep {sweep_param} across predefined values in the Parameter Sweep runner",
                what_to_keep_constant=f"Dataset, target column, test split ({test_size}), and random seed ({random_state})",
                what_to_measure="Weighted F1-score across sweep values",
                why_useful=f"Evaluates sensitivity of {model_name} to {sweep_param} without changing the data partition.",
                expected_support_or_weakening=f"Higher or more stable F1 above {f1_str} supports tuning {sweep_param}; flat scores indicate insensitivity.",
                can_run_predefined=True,
                recommended_runner_config={
                    "experiment_type": "Parameter Sweep",
                    "model_choice": model_name,
                    "sweep_param": sweep_param,
                },
            ),
            NextExperimentRecommendation(
                title=f"Controlled Comparison vs {alt_model}",
                what_to_change=f"Switch classifier from {model_name} to {alt_model}",
                what_to_keep_constant=f"Same dataset, target column, test split ({test_size}), and random seed ({random_state})",
                what_to_measure="Accuracy, weighted F1-score, and confusion matrix misclassifications",
                why_useful=f"Directly compares {model_name} against {alt_model} under identical train/test splits.",
                expected_support_or_weakening=f"If {alt_model} outperforms {acc_pct}, it weakens the advantage of {model_name} on this dataset.",
                can_run_predefined=True,
                recommended_runner_config={
                    "experiment_type": "Classification",
                    "model_choice": alt_model,
                },
            ),
        ]

    elif exp_type == "regression":
        mae = metrics.get("mae")
        rmse = metrics.get("rmse")
        r2 = metrics.get("r2_score")

        if isinstance(r2, (int, float)):
            if r2 >= 0.60:
                status = "Supported"
                fit_desc = "strong"
            elif r2 >= 0.25:
                status = "Inconclusive"
                fit_desc = "moderate"
            else:
                status = "Not Supported"
                fit_desc = "weak"
            r2_str = f"{r2:.4f}"
            var_pct = f"{max(0.0, r2) * 100:.1f}%"
        else:
            status = "Inconclusive"
            fit_desc = "unverified"
            r2_str = "N/A"
            var_pct = "N/A"

        mae_str = f"{mae:.4f}" if isinstance(mae, (int, float)) else "N/A"
        rmse_str = f"{rmse:.4f}" if isinstance(rmse, (int, float)) else "N/A"

        summary = (
            f"The {model_name} regressor achieved MAE = {mae_str}, RMSE = {rmse_str}, "
            f"and R² = {r2_str}{split_note}."
        )
        if isinstance(r2, (int, float)) and r2 < 0:
            what_suggests = (
                f"A negative R² ({r2_str}) indicates that predictions underperformed a constant mean-value baseline on this test split."
            )
        else:
            what_suggests = (
                f"An R² of {r2_str} indicates {fit_desc} explanatory fit, accounting for {var_pct} of target variance on the test split."
            )

        reasons = [
            f"Error metrics (MAE = {mae_str}, RMSE = {rmse_str}) reflect out-of-sample residuals after numeric scaling and imputation."
        ]
        if isinstance(mae, (int, float)) and isinstance(rmse, (int, float)) and mae > 0:
            ratio = rmse / mae
            if ratio > 1.35:
                reasons.append(f"RMSE/MAE ratio ({ratio:.2f}) indicates that larger error outliers are increasing squared error.")
            else:
                reasons.append(f"RMSE/MAE ratio ({ratio:.2f}) suggests relatively uniform residual errors across test samples.")

        alt_model = "Linear Regression" if "Random Forest" in model_name else "Random Forest Regressor"
        recs = [
            NextExperimentRecommendation(
                title="Tree Depth Parameter Sweep" if "Random Forest" in model_name else f"Model Comparison vs {alt_model}",
                what_to_change="Sweep max_depth across [2, 4, 6, 8, 12, 16]" if "Random Forest" in model_name else f"Switch regressor to {alt_model}",
                what_to_keep_constant=f"Dataset, target column, test split ({test_size}), and random seed ({random_state})",
                what_to_measure="Test R², RMSE, and MAE",
                why_useful="Tests whether controlling tree depth or model nonlinearity improves out-of-sample error.",
                expected_support_or_weakening=f"Lower RMSE than {rmse_str} and higher R² than {r2_str} supports the alternative configuration.",
                can_run_predefined=True,
                recommended_runner_config={
                    "experiment_type": "Parameter Sweep" if "Random Forest" in model_name else "Regression",
                    "model_choice": "Random Forest Regressor" if "Random Forest" in model_name else alt_model,
                },
            )
        ]

    elif exp_type == "clustering":
        k = metrics.get("n_clusters", config.get("n_clusters"))
        inertia = metrics.get("inertia")
        sil = metrics.get("silhouette_score")
        pca_var = metrics.get("pca_explained_variance_ratio")

        if isinstance(sil, (int, float)):
            if sil >= 0.50:
                status = "Supported"
                sep_desc = "well-separated"
            elif sil >= 0.25:
                status = "Inconclusive"
                sep_desc = "moderately overlapping"
            else:
                status = "Not Supported"
                sep_desc = "weakly separated"
            sil_str = f"{sil:.4f}"
        else:
            status = "Inconclusive"
            sep_desc = "unverified"
            sil_str = "N/A"

        pca_note = (
            f" The 2D PCA projection retains {sum(pca_var) * 100:.1f}% of total feature variance."
            if isinstance(pca_var, list) and pca_var
            else ""
        )
        summary = (
            f"K-Means clustering (k = {k}) produced inertia = {inertia} and silhouette score = {sil_str}.{pca_note}"
        )
        what_suggests = (
            f"A silhouette score of {sil_str} suggests {sep_desc} clusters in standardized feature space."
        )
        reasons = [
            f"Cluster assignments were computed on standardized numeric features with k = {k} and random seed {config.get('random_state', 42)}."
        ]
        recs = [
            NextExperimentRecommendation(
                title="Cluster Count (k) Sensitivity Check",
                what_to_change="Vary number of clusters k (e.g., k = 2, 3, 4, 5)",
                what_to_keep_constant=f"Same dataset, standardized numeric features, and random seed ({config.get('random_state', 42)})",
                what_to_measure="Silhouette score and inertia across k values",
                why_useful="Compares cluster cohesion and separation across candidate cluster counts.",
                expected_support_or_weakening=f"Higher silhouette score than {sil_str} indicates a cleaner natural grouping.",
                can_run_predefined=True,
                recommended_runner_config={"experiment_type": "Clustering"},
            )
        ]

    else:
        # Parameter sweep or other predefined workflow
        swept_model = config.get("model_type", model_name)
        param_name = config.get("param_name", "parameter")
        param_values = config.get("param_values", [])
        steps = metrics.get("sweep_steps", len(param_values) if isinstance(param_values, list) else "N/A")

        status = "Inconclusive"
        summary = (
            f"Parameter sweep on {swept_model} evaluated {steps} configurations of '{param_name}' "
            f"({param_values}){split_note}."
        )
        what_suggests = (
            f"The sweep curve visualizes how varying '{param_name}' changes test performance under a fixed data split."
        )
        reasons = [
            f"All {steps} sweep runs held the train/test split and random seed ({random_state}) constant while varying '{param_name}'."
        ]
        recs = [
            NextExperimentRecommendation(
                title=f"Evaluate Best {swept_model} Configuration",
                what_to_change=f"Run a standalone experiment comparing {swept_model} against a baseline model",
                what_to_keep_constant=f"Test split ({test_size}) and random seed ({random_state})",
                what_to_measure="Full metric suite and confusion matrix or residual plot",
                why_useful="Inspects per-class or residual behavior for the best parameter from the sweep.",
                expected_support_or_weakening="Consistent improvements across precision/recall or RMSE/R² strengthen empirical support.",
                can_run_predefined=True,
            )
        ]

    interp = InterpretationResult(
        summary=summary,
        what_results_suggest=what_suggests,
        hypothesis_status=status,
        possible_reasons=reasons,
        limitations=[
            "Rule-based fallback summary: derived deterministically from recorded run metrics without LLM domain synthesis.",
            "Metrics reflect a single train/test partition without nested cross-validation or external test validation.",
            "Statistical fit or correlation does not establish causal mechanisms.",
        ],
    )
    return interp, recs


def build_rule_based_analysis(
    run_record: Dict[str, Any],
    fallback_reason: str = "api_key_missing",
    retry_after: Optional[str] = None,
    quota_message: Optional[str] = None,
) -> Dict[str, Any]:
    """Builds a labeled deterministic rule-based analysis package from recorded metrics."""
    exp_type = run_record["experiment_type"]
    config = run_record["config"]
    metrics = run_record["metrics"]
    model_name = config.get("model_type", run_record.get("model_name", exp_type.title()))

    interp, recs = _build_rule_based_parts(exp_type, model_name, config, metrics)
    interp_dict = interp.model_dump()
    interp_dict["source"] = "rule_based"
    interp_dict["source_label"] = RULE_BASED_LABEL
    interp_dict["fallback_reason"] = fallback_reason
    if retry_after:
        interp_dict["retry_after"] = retry_after

    return {
        "interpretation": interp_dict,
        "recommendations": [r.model_dump() for r in recs],
        "source": "rule_based",
        "source_label": RULE_BASED_LABEL,
        "quota_exhausted": fallback_reason == "quota_exhausted",
        "quota_message": quota_message,
        "retry_after": retry_after,
    }


def analyze_and_interpret_run(
    workspace: Dict[str, Any],
    run_record: Dict[str, Any],
    plan_dict: Optional[Dict[str, Any]] = None
) -> Dict[str, Any]:
    """Generates scientific interpretation and recommendations, falling back gracefully on missing key or 429 quota."""
    ws_id = workspace["id"]
    rq = workspace["research_question"]
    hyp = workspace.get("hypothesis", "")

    exp_type = run_record["experiment_type"]
    config = run_record["config"]
    metrics = run_record["metrics"]
    model_name = config.get("model_type", run_record.get("model_name", "Model"))

    configured, _ = is_gemini_configured()
    if not configured:
        return build_rule_based_analysis(run_record, fallback_reason="api_key_missing")

    try:
        interp = interpret_results_llm(
            research_question=rq,
            hypothesis=hyp,
            experiment_type=exp_type,
            model_name=model_name,
            config=config,
            metrics=metrics,
            plan_context=str(plan_dict.get("objective") if plan_dict else "")
        )
    except GeminiQuotaExhaustedError as qe:
        return build_rule_based_analysis(
            run_record,
            fallback_reason="quota_exhausted",
            retry_after=qe.retry_after,
            quota_message=str(qe),
        )

    interp_dict = interp.model_dump()
    interp_dict["source"] = "gemini"
    interp_dict["source_label"] = GEMINI_LABEL

    # Retrieve literature context for grounding follow-up recommendations
    evidence_chunks = retrieve_relevant_chunks(ws_id, query=rq, top_k=3)
    ev_text = "\n".join([f"[{c.source_filename} p.{c.page_number}]: {c.content}" for c in evidence_chunks])

    try:
        recs = recommend_next_experiments_llm(
            research_question=rq,
            hypothesis=hyp,
            current_model=model_name,
            current_metrics=metrics,
            interpretation_summary=interp.summary,
            evidence_context=ev_text
        )
        return {
            "interpretation": interp_dict,
            "recommendations": [r.model_dump() for r in recs],
            "source": "gemini",
            "source_label": GEMINI_LABEL,
            "quota_exhausted": False,
            "quota_message": None,
            "retry_after": None,
        }
    except GeminiQuotaExhaustedError as qe:
        # Preserve the Gemini interpretation while providing rule-based follow-up recommendations
        _, fallback_recs = _build_rule_based_parts(exp_type, model_name, config, metrics)
        return {
            "interpretation": interp_dict,
            "recommendations": [r.model_dump() for r in fallback_recs],
            "source": "gemini_partial",
            "source_label": GEMINI_LABEL,
            "quota_exhausted": True,
            "quota_message": str(qe),
            "retry_after": qe.retry_after,
        }
