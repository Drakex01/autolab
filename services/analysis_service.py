def _extract_run_signature(run: Dict[str, Any]) -> Dict[str, Any]:
    """Extracts comparability metadata from a run record."""
    cfg = run.get("config") or {}
    dataset_name = str(run.get("dataset_name") or "").strip()
    raw_target = run.get("target_column") if run.get("target_column") is not None else cfg.get("target_column")
    target_column = str(raw_target).strip() if raw_target is not None and str(raw_target).strip() else None
    exp_type = str(run.get("experiment_type") or "").strip().lower()

    raw_split = cfg.get("test_size")
    test_size = float(raw_split) if isinstance(raw_split, (int, float)) else None

    raw_seed = cfg.get("random_state")
    random_state = int(raw_seed) if isinstance(raw_seed, (int, float)) and not isinstance(raw_seed, bool) else None

    model_type = str(cfg.get("model_type") or run.get("model_name") or "").strip()
    return {
        "dataset_name": dataset_name,
        "target_column": target_column,
        "experiment_type": exp_type,
        "test_size": test_size,
        "random_state": random_state,
        "model_type": model_type,
    }


def _splits_equal(a: Optional[float], b: Optional[float]) -> bool:
    if a is None or b is None:
        return a is b
    return abs(a - b) < 1e-9


def find_comparable_runs(
    selected_run: Dict[str, Any],
    workspace_runs: Optional[List[Dict[str, Any]]] = None,
) -> Dict[str, Any]:
    """
    Identifies workspace runs comparable to selected_run on:
      - Same dataset
      - Same target column
      - Same experiment type
      - Same train-test split
      - Same random seed
    Also detects completed parameter sweeps and tested random seeds.
    """
    if workspace_runs is None:
        ws_id = selected_run.get("workspace_id")
        workspace_runs = list_experiment_runs(ws_id) if ws_id is not None else [selected_run]

    # Ensure selected_run is included even if passed directly in unit tests
    all_runs = list(workspace_runs)
    sel_id = selected_run.get("id")
    if sel_id is None or not any(r.get("id") == sel_id for r in all_runs):
        all_runs.insert(0, selected_run)

    sel_sig = _extract_run_signature(selected_run)

    comparable_runs: List[Dict[str, Any]] = []
    non_comparable_runs: List[Dict[str, Any]] = []
    completed_sweeps: set[Tuple[str, str]] = set()
    completed_seeds: set[int] = set()

    for run in all_runs:
        metrics = run.get("metrics")
        if not isinstance(metrics, dict) or not metrics:
            continue

        sig = _extract_run_signature(run)

        # Track completed parameter sweeps matching dataset/target/split/seed
        if (
            sig["experiment_type"] == "parameter_sweep"
            and sig["dataset_name"] == sel_sig["dataset_name"]
            and sig["target_column"] == sel_sig["target_column"]
            and _splits_equal(sig["test_size"], sel_sig["test_size"])
            and sig["random_state"] == sel_sig["random_state"]
        ):
            cfg = run.get("config") or {}
            p_name = str(cfg.get("param_name") or "").strip()
            if sig["model_type"] and p_name:
                completed_sweeps.add((sig["model_type"], p_name))

        # Track distinct seeds tested on the same dataset/target/type/split
        if (
            sig["dataset_name"] == sel_sig["dataset_name"]
            and sig["target_column"] == sel_sig["target_column"]
            and sig["experiment_type"] == sel_sig["experiment_type"]
            and _splits_equal(sig["test_size"], sel_sig["test_size"])
            and sig["random_state"] is not None
        ):
            completed_seeds.add(sig["random_state"])

        mismatches: List[str] = []
        if sig["dataset_name"] != sel_sig["dataset_name"]:
            mismatches.append(f"dataset ('{sig['dataset_name']}' vs '{sel_sig['dataset_name']}')")
        if sig["target_column"] != sel_sig["target_column"]:
            mismatches.append(f"target_column ({sig['target_column']} vs {sel_sig['target_column']})")
        if sig["experiment_type"] != sel_sig["experiment_type"]:
            mismatches.append(f"experiment_type ('{sig['experiment_type']}' vs '{sel_sig['experiment_type']}')")
        if not _splits_equal(sig["test_size"], sel_sig["test_size"]):
            mismatches.append(f"test_size ({sig['test_size']} vs {sel_sig['test_size']})")
        if sig["random_state"] != sel_sig["random_state"]:
            mismatches.append(f"random_state ({sig['random_state']} vs {sel_sig['random_state']})")

        if not mismatches:
            comparable_runs.append(run)
        else:
            non_comparable_runs.append({
                "run_id": run.get("id"),
                "model_type": sig["model_type"] or sig["experiment_type"],
                "mismatches": mismatches,
            })

    completed_models = {
        _extract_run_signature(r)["model_type"]
        for r in comparable_runs
        if _extract_run_signature(r)["model_type"]
    }

    return {
        "selected_signature": sel_sig,
        "target_column_verified": sel_sig["target_column"] is not None,
        "comparable_runs": comparable_runs,
        "non_comparable_runs": non_comparable_runs,
        "completed_models": completed_models,
        "completed_sweeps": completed_sweeps,
        "completed_seeds": completed_seeds,
    }


def _extract_class_level_data(run: Dict[str, Any]) -> Dict[str, Any]:
    """
    Extracts class-specific precision, recall, F1-score, and confusion matrix if recorded.
    Never infers per-class scores from weighted averages.
    """
    metrics = run.get("metrics") or {}
    cfg = run.get("config") or {}

    cm = (
        metrics.get("confusion_matrix")
        if metrics.get("confusion_matrix") is not None
        else run.get("confusion_matrix")
        if run.get("confusion_matrix") is not None
        else cfg.get("confusion_matrix")
    )
    classes = (
        metrics.get("classes")
        if metrics.get("classes") is not None
        else run.get("classes")
        if run.get("classes") is not None
        else cfg.get("classes")
    )
    recorded_per_class = (
        metrics.get("per_class_metrics")
        or metrics.get("classification_report")
        or run.get("per_class_metrics")
        or cfg.get("per_class_metrics")
    )

    per_class: Dict[str, Dict[str, Any]] = {}
    source: Optional[str] = None

    if isinstance(recorded_per_class, dict) and recorded_per_class:
        for cls_key, vals in recorded_per_class.items():
            if str(cls_key) in {"accuracy", "macro avg", "weighted avg"} or not isinstance(vals, dict):
                continue
            p = vals.get("precision")
            r = vals.get("recall")
            f1 = vals.get("f1_score", vals.get("f1-score"))
            sup = vals.get("support")
            if any(isinstance(x, (int, float)) for x in (p, r, f1)):
                per_class[str(cls_key)] = {
                    "precision": round(float(p), 4) if isinstance(p, (int, float)) else None,
                    "recall": round(float(r), 4) if isinstance(r, (int, float)) else None,
                    "f1_score": round(float(f1), 4) if isinstance(f1, (int, float)) else None,
                    "support": int(sup) if isinstance(sup, (int, float)) else None,
                }
        if per_class:
            source = "recorded_per_class"

    valid_cm = (
        isinstance(cm, list)
        and len(cm) >= 2
        and all(isinstance(row, list) and len(row) == len(cm) for row in cm)
    )
    if valid_cm and not per_class:
        labels = [str(c) for c in classes] if isinstance(classes, list) and len(classes) == len(cm) else [f"Class {i}" for i in range(len(cm))]
        for idx, label in enumerate(labels):
            tp = float(cm[idx][idx])
            row_sum = float(sum(cm[idx]))
            col_sum = float(sum(cm[r_idx][idx] for r_idx in range(len(cm))))
            prec = tp / col_sum if col_sum > 0 else 0.0
            rec = tp / row_sum if row_sum > 0 else 0.0
            f1 = (2.0 * prec * rec / (prec + rec)) if (prec + rec) > 0 else 0.0
            per_class[label] = {
                "precision": round(prec, 4),
                "recall": round(rec, 4),
                "f1_score": round(f1, 4),
                "support": int(row_sum),
            }
        source = "derived_from_confusion_matrix"

    return {
        "available": bool(per_class or valid_cm),
        "source": source,
        "classes": [str(c) for c in classes] if isinstance(classes, list) else list(per_class.keys()) if per_class else None,
        "confusion_matrix": cm if valid_cm else None,
        "per_class": per_class if per_class else None,
    }


def _pick_representative_run(
    comparable_runs: List[Dict[str, Any]],
    selected_run: Dict[str, Any],
    target_model: str,
) -> Optional[Dict[str, Any]]:
    """Selects selected_run if it matches target_model, otherwise the most recent comparable run for target_model."""
    if _extract_run_signature(selected_run)["model_type"] == target_model:
        return selected_run
    matching = [
        r for r in comparable_runs
        if _extract_run_signature(r)["model_type"] == target_model
    ]
    if not matching:
        return None
    matching.sort(key=lambda r: (str(r.get("created_at") or ""), int(r.get("id") or 0)), reverse=True)
    return matching[0]


def build_comparative_analysis(
    selected_run: Dict[str, Any],
    workspace_runs: Optional[List[Dict[str, Any]]] = None,
    selected_metrics: Optional[List[str]] = None,
) -> Dict[str, Any]:
    """
    Compares comparable Random Forest and Logistic Regression runs on shared evaluation metrics
    and class-level metrics / confusion matrices wherever recorded.
    """
    discovery = find_comparable_runs(selected_run, workspace_runs)
    sel_sig = discovery["selected_signature"]
    comparable_runs = discovery["comparable_runs"]
    completed_models = discovery["completed_models"]
    completed_sweeps = discovery["completed_sweeps"]
    completed_seeds = discovery["completed_seeds"]

    rf_run = _pick_representative_run(comparable_runs, selected_run, "Random Forest")
    lr_run = _pick_representative_run(comparable_runs, selected_run, "Logistic Regression")

    completed_comparisons: List[str] = []
    if rf_run is not None and lr_run is not None:
        split_label = f"{sel_sig['test_size']}" if sel_sig["test_size"] is not None else "N/A"
        seed_label = f"{sel_sig['random_state']}" if sel_sig["random_state"] is not None else "N/A"
        completed_comparisons.append(
            f"Logistic Regression vs Random Forest on '{sel_sig['dataset_name']}' "
            f"(split={split_label}, seed={seed_label})"
        )
    for m_name, p_name in sorted(completed_sweeps):
        completed_comparisons.append(f"{m_name} '{p_name}' parameter sweep")
    if len(completed_seeds) >= 2:
        completed_comparisons.append(
            f"Multi-seed comparison across seeds {sorted(completed_seeds)}"
        )

    # Handle missing counterpart or non-comparable runs
    if sel_sig["experiment_type"] != "classification" or rf_run is None or lr_run is None:
        if sel_sig["experiment_type"] == "classification":
            other_model = "Logistic Regression" if rf_run is not None else "Random Forest"
            other_mismatched = [
                nc for nc in discovery["non_comparable_runs"]
                if nc.get("model_type") == other_model
            ]
            if other_mismatched:
                status = "not_comparable"
                reason = (
                    f"Runs for {other_model} exist in the workspace but are not comparable to Run #{selected_run.get('id')} "
                    f"due to differing settings: {', '.join(other_mismatched[0]['mismatches'])}."
                )
            else:
                status = "incomplete"
                reason = (
                    f"No comparable {other_model} run was found in the workspace with matching dataset "
                    f"('{sel_sig['dataset_name']}'), target column, experiment type, test split ({sel_sig['test_size']}), "
                    f"and random seed ({sel_sig['random_state']})."
                )
        else:
            status = "single_run"
            reason = f"Comparative Logistic Regression vs Random Forest analysis applies to classification runs (selected: {sel_sig['experiment_type']})."

        return {
            "comparison_available": False,
            "comparison_status": status,
            "reason": reason,
            "hypothesis_status": "Inconclusive",
            "selected_signature": sel_sig,
            "target_column_verified": discovery["target_column_verified"],
            "comparable_run_ids": [r.get("id") for r in comparable_runs if r.get("id") is not None],
            "non_comparable_runs": discovery["non_comparable_runs"],
            "completed_models": sorted(completed_models),
            "completed_sweeps": sorted(list(completed_sweeps)),
            "completed_seeds": sorted(list(completed_seeds)),
            "completed_comparisons": completed_comparisons,
            "metrics_table": [],
            "class_level_comparison": {
                "available": False,
                "note": "No comparable model pair available for class-level comparison.",
            },
        }

    # Both Random Forest and Logistic Regression comparable runs exist
    rf_metrics = rf_run.get("metrics") or {}
    lr_metrics = lr_run.get("metrics") or {}

    shared_numeric = [
        k for k in CLASSIFICATION_METRIC_ORDER
        if isinstance(rf_metrics.get(k), (int, float))
        and not isinstance(rf_metrics.get(k), bool)
        and isinstance(lr_metrics.get(k), (int, float))
        and not isinstance(lr_metrics.get(k), bool)
    ]
    for k in sorted(set(rf_metrics.keys()) & set(lr_metrics.keys())):
        if (
            k not in shared_numeric
            and k not in _NON_PROPORTION_METRIC_KEYS
            and isinstance(rf_metrics.get(k), (int, float))
            and not isinstance(rf_metrics.get(k), bool)
            and isinstance(lr_metrics.get(k), (int, float))
            and not isinstance(lr_metrics.get(k), bool)
        ):
            shared_numeric.append(k)

    if selected_metrics:
        eval_metrics = [m for m in selected_metrics if m in shared_numeric]
    else:
        eval_metrics = shared_numeric

    metrics_table: List[Dict[str, Any]] = []
    rf_wins = 0
    lr_wins = 0
    ties = 0

    for m_key in eval_metrics:
        rf_val = float(rf_metrics[m_key])
        lr_val = float(lr_metrics[m_key])
        diff = rf_val - lr_val
        signed_pp = round(diff * 100.0, 2)
        abs_pp = round(abs(diff) * 100.0, 2)

        if diff > 1e-6:
            winner = "Random Forest"
            rf_wins += 1
        elif diff < -1e-6:
            winner = "Logistic Regression"
            lr_wins += 1
        else:
            winner = "Tie"
            ties += 1

        metrics_table.append({
            "metric_key": m_key,
            "metric": METRIC_DISPLAY_NAMES.get(m_key, m_key.replace("_", " ").title()),
            "random_forest": round(rf_val, 4),
            "logistic_regression": round(lr_val, 4),
            "rf_pct": round(rf_val * 100.0, 2),
            "lr_pct": round(lr_val * 100.0, 2),
            "signed_diff_pp": signed_pp,
            "abs_diff_pp": abs_pp,
            "winner": winner,
        })

    if not metrics_table:
        hypothesis_status = "Inconclusive"
        comparison_status = "incomplete"
    elif rf_wins > 0 and lr_wins == 0:
        hypothesis_status = "Supported"
        comparison_status = "compared"
    elif lr_wins > 0 and rf_wins == 0:
        hypothesis_status = "Not Supported"
        comparison_status = "compared"
    else:
        hypothesis_status = "Inconclusive"
        comparison_status = "tied" if (rf_wins == 0 and lr_wins == 0) else "mixed"

    # Class-specific metrics and confusion matrix comparison (only wherever recorded)
    rf_cls = _extract_class_level_data(rf_run)
    lr_cls = _extract_class_level_data(lr_run)

    if rf_cls["available"] and lr_cls["available"] and rf_cls["per_class"] and lr_cls["per_class"]:
        shared_classes = [c for c in rf_cls["per_class"].keys() if c in lr_cls["per_class"]]
        per_class_rows = []
        for cls_label in shared_classes:
            rc = rf_cls["per_class"][cls_label]
            lc = lr_cls["per_class"][cls_label]
            p_diff = round((rc["precision"] - lc["precision"]) * 100.0, 2) if (rc["precision"] is not None and lc["precision"] is not None) else None
            r_diff = round((rc["recall"] - lc["recall"]) * 100.0, 2) if (rc["recall"] is not None and lc["recall"] is not None) else None
            f1_diff = round((rc["f1_score"] - lc["f1_score"]) * 100.0, 2) if (rc["f1_score"] is not None and lc["f1_score"] is not None) else None
            per_class_rows.append({
                "class": cls_label,
                "rf_precision": rc["precision"],
                "lr_precision": lc["precision"],
                "precision_abs_diff_pp": round(abs(p_diff), 2) if p_diff is not None else None,
                "rf_recall": rc["recall"],
                "lr_recall": lc["recall"],
                "recall_abs_diff_pp": round(abs(r_diff), 2) if r_diff is not None else None,
                "rf_f1": rc["f1_score"],
                "lr_f1": lc["f1_score"],
                "f1_abs_diff_pp": round(abs(f1_diff), 2) if f1_diff is not None else None,
                "rf_support": rc["support"],
                "lr_support": lc["support"],
            })

        class_level_comparison = {
            "available": True,
            "source_rf": rf_cls["source"],
            "source_lr": lr_cls["source"],
            "per_class_rows": per_class_rows,
            "rf_confusion_matrix": rf_cls["confusion_matrix"],
            "lr_confusion_matrix": lr_cls["confusion_matrix"],
            "rf_classes": rf_cls["classes"],
            "lr_classes": lr_cls["classes"],
            "note": "Class-specific precision, recall, F1-score, and confusion matrices extracted directly from recorded run outputs.",
        }
    else:
        missing_models = []
        if not rf_cls["available"]:
            missing_models.append("Random Forest")
        if not lr_cls["available"]:
            missing_models.append("Logistic Regression")
        class_level_comparison = {
            "available": False,
            "missing_models": missing_models,
            "rf_confusion_matrix": rf_cls["confusion_matrix"],
            "lr_confusion_matrix": lr_cls["confusion_matrix"],
            "note": (
                f"Class-specific precision, recall, F1-score, and confusion matrices were not recorded in SQLite for "
                f"{' and '.join(missing_models)}. Only aggregate weighted metrics were saved; class-level performance "
                f"cannot be inferred from weighted averages."
            ),
        }

    return {
        "comparison_available": True,
        "comparison_status": comparison_status,
        "hypothesis_status": hypothesis_status,
        "selected_signature": sel_sig,
        "target_column_verified": discovery["target_column_verified"],
        "rf_run_id": rf_run.get("id"),
        "lr_run_id": lr_run.get("id"),
        "comparable_run_ids": [r.get("id") for r in comparable_runs if r.get("id") is not None],
        "non_comparable_runs": discovery["non_comparable_runs"],
        "completed_models": sorted(completed_models),
        "completed_sweeps": sorted(list(completed_sweeps)),
        "completed_seeds": sorted(list(completed_seeds)),
        "completed_comparisons": completed_comparisons,
        "selected_metrics": eval_metrics,
        "metrics_table": metrics_table,
        "rf_wins": rf_wins,
        "lr_wins": lr_wins,
        "ties": ties,
        "class_level_comparison": class_level_comparison,
    }


def _build_non_redundant_classification_recommendations(
    selected_run: Dict[str, Any],
    comparison_info: Dict[str, Any],
) -> List[NextExperimentRecommendation]:
    """Builds concrete, non-redundant follow-up recommendations excluding completed comparisons and sweeps."""
    sel_sig = comparison_info["selected_signature"]
    completed_models = set(comparison_info.get("completed_models", []))
    completed_sweeps = {tuple(x) for x in comparison_info.get("completed_sweeps", [])}
    completed_seeds = set(comparison_info.get("completed_seeds", []))

    test_size = sel_sig.get("test_size")
    random_state = sel_sig.get("random_state")
    dataset_name = sel_sig.get("dataset_name") or "current dataset"
    both_compared = {"Random Forest", "Logistic Regression"}.issubset(completed_models)

    recs: List[NextExperimentRecommendation] = []

    # If one model hasn't been run yet on comparable settings, recommend completing that comparison first
    if not both_compared:
        missing_model = "Logistic Regression" if "Random Forest" in completed_models else "Random Forest"
        recs.append(
            NextExperimentRecommendation(
                title=f"Run Comparable {missing_model} Baseline",
                what_to_change=f"Train and evaluate {missing_model} on '{dataset_name}'",
                what_to_keep_constant=f"Same dataset ('{dataset_name}'), target column, test split ({test_size}), and random seed ({random_state})",
                what_to_measure="Accuracy, weighted precision, weighted recall, weighted F1, and confusion matrix",
                why_useful=f"Completes a controlled side-by-side comparison against {sel_sig.get('model_type') or 'the current model'} under identical split conditions.",
                expected_support_or_weakening=f"Allows evaluating whether Random Forest outperforms Logistic Regression on '{dataset_name}'.",
                can_run_predefined=True,
                recommended_runner_config={
                    "experiment_type": "Classification",
                    "model_choice": missing_model,
                },
            )
        )

    # 1. Logistic Regression C hyperparameter sweep (skip if already swept)
    if ("Logistic Regression", "C") not in completed_sweeps:
        recs.append(
            NextExperimentRecommendation(
                title="Logistic Regression C Hyperparameter Sweep",
                what_to_change="Vary inverse regularization strength C across [0.01, 0.1, 1.0, 10.0, 50.0]",
                what_to_keep_constant=f"Dataset ('{dataset_name}'), target column, test split ({test_size}), and random seed ({random_state})",
                what_to_measure="Weighted F1-score, accuracy, and regularization sensitivity across C values",
                why_useful="Tests whether under- or over-regularization constrained the linear Logistic Regression baseline.",
                expected_support_or_weakening="If tuned C matches or exceeds Random Forest, linear decision boundaries may be sufficient with proper regularization.",
                can_run_predefined=True,
                recommended_runner_config={
                    "experiment_type": "Parameter Sweep",
                    "model_choice": "Logistic Regression",
                    "sweep_param": "C",
                },
            )
        )

    # 2. Random Forest hyperparameter tuning (skip parameters already swept)
    rf_n_done = ("Random Forest", "n_estimators") in completed_sweeps
    rf_d_done = ("Random Forest", "max_depth") in completed_sweeps
    if not (rf_n_done and rf_d_done):
        if rf_n_done:
            rf_param = "max_depth"
            rf_vals = "[2, 4, 6, 8, 12, 16]"
        elif rf_d_done:
            rf_param = "n_estimators"
            rf_vals = "[10, 25, 50, 100, 200]"
        else:
            rf_param = "max_depth"
            rf_vals = "[2, 4, 6, 8, 12, 16] (or n_estimators in [10, 25, 50, 100, 200])"
        recs.append(
            NextExperimentRecommendation(
                title=f"Random Forest Hyperparameter Tuning ({rf_param})",
                what_to_change=f"Sweep Random Forest {rf_param} across {rf_vals}",
                what_to_keep_constant=f"Dataset ('{dataset_name}'), target column, test split ({test_size}), and random seed ({random_state})",
                what_to_measure="Weighted F1-score and generalization stability across tree complexity settings",
                why_useful="Evaluates whether limiting tree depth or adjusting ensemble size reduces variance and improves out-of-sample generalization.",
                expected_support_or_weakening="Consistent or higher test F1 at moderate depth supports genuine nonlinear structure rather than overfitting.",
                can_run_predefined=True,
                recommended_runner_config={
                    "experiment_type": "Parameter Sweep",
                    "model_choice": "Random Forest",
                    "sweep_param": rf_param,
                },
            )
        )

    # 3. Stratified cross-validation
    recs.append(
        NextExperimentRecommendation(
            title="Stratified K-Fold Cross-Validation",
            what_to_change="Evaluate both Logistic Regression and Random Forest across 5-fold or 10-fold stratified cross-validation instead of a single split",
            what_to_keep_constant=f"Same dataset ('{dataset_name}'), preprocessing pipeline, and model hyperparameters",
            what_to_measure="Mean and standard deviation of accuracy, F1, precision, and recall across folds",
            why_useful="Quantifies fold-to-fold variance and verifies whether the observed difference persists across multiple partitions of the dataset.",
            expected_support_or_weakening="Consistent fold-level gains across folds strengthen the comparison; overlapping fold intervals indicate split sensitivity.",
            can_run_predefined=False,
        )
    )

    # 4. Evaluation of recall and false-negative reduction
    cls_info = comparison_info.get("class_level_comparison") or {}
    if cls_info.get("available"):
        fn_why = "Compares per-class recall and confusion-matrix false negatives directly between both models to assess missed positive detections."
    else:
        fn_why = "Class-level recall and confusion matrices were not saved in the SQLite run history; inspecting per-class false negatives prevents weighted averages from masking minority-class misses."
    recs.append(
        NextExperimentRecommendation(
            title="Evaluation of Recall and False-Negative Reduction",
            what_to_change="Inspect per-class recall, confusion matrices, and decision-threshold or class-weight adjustments",
            what_to_keep_constant=f"Same dataset ('{dataset_name}'), target column, and train/test split ({test_size})",
            what_to_measure="Class-specific recall, false-negative counts, and minority-class F1-score",
            why_useful=fn_why,
            expected_support_or_weakening="Lower false-negative rate and higher positive-class recall indicate stronger reliability for risk-sensitive predictions.",
            can_run_predefined=False,
        )
    )

    # 5. Comparison across different random seeds (skip if >= 2 distinct seeds already tested)
    if len(completed_seeds) < 2:
        alt_seed = 123 if random_state != 123 else 7
        recs.append(
            NextExperimentRecommendation(
                title="Comparison Across Different Random Seeds",
                what_to_change=f"Re-run both Random Forest and Logistic Regression with additional random_state seeds (e.g., {alt_seed}, 7, 99)",
                what_to_keep_constant=f"Same dataset ('{dataset_name}'), target column, and test split ({test_size})",
                what_to_measure="Accuracy and weighted F1-score spread between Random Forest and Logistic Regression across seeds",
                why_useful=f"Single-seed results (seed {random_state}) can depend on which samples fall into the test fold.",
                expected_support_or_weakening="If Random Forest consistently leads across multiple seeds, the finding is less likely to be an artifact of one split.",
                can_run_predefined=True,
                recommended_runner_config={
                    "experiment_type": "Classification",
                    "model_choice": "Random Forest",
                    "suggested_param": f"random_state={alt_seed}",
                },
            )
        )

    return recs


def _filter_redundant_llm_recommendations(
    llm_recs: List[NextExperimentRecommendation],
    comparison_info: Dict[str, Any],
    fallback_recs: List[NextExperimentRecommendation],
) -> List[NextExperimentRecommendation]:
    """Removes LLM recommendations that repeat already-completed comparisons or sweeps."""
    completed_models = set(comparison_info.get("completed_models", []))
    completed_sweeps = {tuple(x) for x in comparison_info.get("completed_sweeps", [])}
    both_compared = {"Random Forest", "Logistic Regression"}.issubset(completed_models)

    filtered: List[NextExperimentRecommendation] = []
    for rec in llm_recs:
        text = f"{rec.title} {rec.what_to_change} {rec.why_useful}".lower()
        cfg = rec.recommended_runner_config or {}
        cfg_model = str(cfg.get("model_choice") or "")
        cfg_param = str(cfg.get("sweep_param") or cfg.get("suggested_param") or "")

        # Block repeating Logistic Regression vs Random Forest comparison
        if both_compared and (
            ("compare" in text or "baseline" in text or "contrast" in text or "switch" in text)
            and ("logistic regression" in text and "random forest" in text)
        ):
            continue
        if both_compared and str(cfg.get("experiment_type") or "").lower() == "classification" and "seed" not in text:
            if cfg_model in {"Logistic Regression", "Random Forest"}:
                continue

        # Block repeating already-completed parameter sweeps
        is_repeated_sweep = False
        for m_done, p_done in completed_sweeps:
            if m_done.lower() in text and p_done.lower() in text:
                is_repeated_sweep = True
            if cfg_model == m_done and p_done and p_done == cfg_param:
                is_repeated_sweep = True
        if is_repeated_sweep:
            continue

        filtered.append(rec)

    if not filtered:
        return fallback_recs
    return filtered


def _build_comparative_rule_based_parts(
    selected_run: Dict[str, Any],
    comparison_info: Dict[str, Any],
) -> Tuple[InterpretationResult, List[NextExperimentRecommendation]]:
    """Generates a strictly metric-grounded deterministic comparative interpretation."""
    sel_sig = comparison_info["selected_signature"]
    dataset_name = sel_sig.get("dataset_name") or "the selected dataset"
    split_val = sel_sig.get("test_size")
    seed_val = sel_sig.get("random_state")
    split_note = (
        f" on a {int((1 - split_val) * 100)}/{int(split_val * 100)} train/test split (seed {seed_val})"
        if isinstance(split_val, (int, float)) and seed_val is not None
        else ""
    )

    metrics_table = comparison_info["metrics_table"]
    hyp_status = comparison_info["hypothesis_status"]
    cls_comp = comparison_info["class_level_comparison"]
    rf_id = comparison_info.get("rf_run_id")
    lr_id = comparison_info.get("lr_run_id")

    metric_parts = [
        f"{row['metric']}: Random Forest {row['rf_pct']:.2f}% vs Logistic Regression {row['lr_pct']:.2f}% "
        f"(signed diff {row['signed_diff_pp']:+.2f} pp, absolute diff {row['abs_diff_pp']:.2f} pp)"
        for row in metrics_table
    ]

    if hyp_status == "Supported":
        summary = (
            f"Across comparable classification runs on '{dataset_name}'{split_note}, Random Forest (Run #{rf_id}) "
            f"outperformed Logistic Regression (Run #{lr_id}) on all {len(metrics_table)} evaluated metric(s): "
            + "; ".join(metric_parts)
            + "."
        )
        what_suggests = (
            f"The recorded out-of-sample metrics support the hypothesis that Random Forest achieves stronger predictive "
            f"performance than Logistic Regression under identical dataset, split, and random-seed conditions."
        )
    elif hyp_status == "Not Supported":
        summary = (
            f"Across comparable classification runs on '{dataset_name}'{split_note}, Logistic Regression (Run #{lr_id}) "
            f"outperformed Random Forest (Run #{rf_id}) on all {len(metrics_table)} evaluated metric(s): "
            + "; ".join(metric_parts)
            + "."
        )
        what_suggests = (
            f"The recorded metrics do not support Random Forest outperforming Logistic Regression on this test partition; "
            f"the linear Logistic Regression model achieved higher scores across the evaluated metrics."
        )
    else:
        summary = (
            f"Comparable classification runs on '{dataset_name}'{split_note} (Random Forest Run #{rf_id} vs "
            f"Logistic Regression Run #{lr_id}) produced {comparison_info.get('comparison_status', 'tied/mixed')} results: "
            + "; ".join(metric_parts)
            + "."
        )
        what_suggests = (
            "The results are inconclusive because the selected evaluation metrics are tied or split between the two models."
        )

    reasons = [
        f"Both models were evaluated on identical comparability criteria: dataset='{dataset_name}', "
        f"experiment_type='classification', test_size={split_val}, random_state={seed_val}."
    ]

    if cls_comp.get("available"):
        cls_notes = []
        for row in cls_comp.get("per_class_rows", []):
            cls_notes.append(
                f"Class '{row['class']}': RF recall={row['rf_recall']}, LR recall={row['lr_recall']} "
                f"(|diff|={row['recall_abs_diff_pp']} pp); RF F1={row['rf_f1']}, LR F1={row['lr_f1']}"
            )
        what_suggests += " Class-specific metrics extracted from recorded outputs: " + "; ".join(cls_notes) + "."
        reasons.append("Class-specific precision, recall, F1-score, and confusion matrices were recorded and compared directly.")
    else:
        reasons.append(cls_comp.get("note", "Class-specific metrics and confusion matrices were not recorded."))

    limitations = [
        "Rule-based comparative summary: derived deterministically from recorded SQLite run metrics without LLM synthesis or statistical significance testing.",
        f"Single train/test split evaluation (test_size={split_val}, random_state={seed_val}); fold-to-fold variance has not been measured via cross-validation.",
    ]
    if not comparison_info.get("target_column_verified", True):
        limitations.append(
            "Target column name was not stored in legacy SQLite config metadata for these runs; comparability assumes both runs targeted the same column."
        )
    if not cls_comp.get("available"):
        limitations.append(
            "Class-specific precision, recall, F1-score, and confusion matrices were not recorded in SQLite; weighted averages were not used to infer per-class performance."
        )

    interp = InterpretationResult(
        summary=summary,
        what_results_suggest=what_suggests,
        hypothesis_status=hyp_status,
        possible_reasons=reasons,
        limitations=limitations,
    )
    recs = _build_non_redundant_classification_recommendations(selected_run, comparison_info)
    return interp, recs


def _is_comparative_hypothesis(workspace: Dict[str, Any]) -> bool:
    """Checks whether the workspace research question or hypothesis compares Random Forest and Logistic Regression."""
    text = f"{workspace.get('research_question', '')} {workspace.get('hypothesis', '')}".lower()
    if "random forest" in text and "logistic regression" in text:
        return True
    comparative_phrases = ("outperform", "perform better", "better than", " vs ", "versus", "compare")
    return any(phrase in text for phrase in comparative_phrases)


def _build_single_run_rule_based_parts(
    exp_type: str,
    model_name: str,
    config: Dict[str, Any],
    metrics: Dict[str, Any],
    selected_run: Optional[Dict[str, Any]] = None,
    comparison_info: Optional[Dict[str, Any]] = None,
    require_comparative: bool = False,
) -> Tuple[InterpretationResult, List[NextExperimentRecommendation]]:
    """Builds a deterministic interpretation and follow-up suggestions strictly from real metrics/config."""
    test_size = config.get("test_size")
    random_state = config.get("random_state")
    split_note = (
        f" on a {int((1 - test_size) * 100)}/{int(test_size * 100)} train/test split (seed {random_state})"
        if isinstance(test_size, (int, float)) and random_state is not None
        else ""
    )

    if exp_type == "classification":
        acc = metrics.get("accuracy")
        prec = metrics.get("precision_weighted")
        rec = metrics.get("recall_weighted")
        f1 = metrics.get("f1_weighted")

        acc_pct = f"{acc * 100:.2f}%" if isinstance(acc, (int, float)) else "N/A"
        f1_str = f"{f1:.4f}" if isinstance(f1, (int, float)) else "N/A"
        prec_str = f"{prec:.4f}" if isinstance(prec, (int, float)) else "N/A"
        rec_str = f"{rec:.4f}" if isinstance(rec, (int, float)) else "N/A"

        # Single-run without comparable counterpart cannot conclude a model-vs-model hypothesis
        if comparison_info is not None and require_comparative:
            status = "Inconclusive"
            reason_note = comparison_info.get("reason", "")
            summary = (
                f"The {model_name} classifier achieved a test accuracy of {acc_pct}, "
                f"weighted F1-score of {f1_str}, precision of {prec_str}, and recall of {rec_str}{split_note}."
            )
            what_suggests = (
                f"Observed single-run metrics ({acc_pct} accuracy, {f1_str} weighted F1) cannot confirm a comparative hypothesis alone. "
                f"{reason_note}"
            )
        else:
            if isinstance(acc, (int, float)):
                status = "Supported" if acc >= 0.85 else "Inconclusive" if acc >= 0.60 else "Not Supported"
            else:
                status = "Inconclusive"
            summary = (
                f"The {model_name} classifier achieved a test accuracy of {acc_pct}, "
                f"weighted F1-score of {f1_str}, precision of {prec_str}, and recall of {rec_str}{split_note}."
            )
            what_suggests = (
                f"Observed test accuracy ({acc_pct}) and weighted F1 ({f1_str}) reflect single-split performance on the held-out set."
            )

        reasons = [
            f"Measured precision ({prec_str}) and recall ({rec_str}) reflect performance after standard scaling and imputation{split_note}."
        ]
        if isinstance(prec, (int, float)) and isinstance(rec, (int, float)):
            gap = abs(prec - rec)
            if gap < 0.05:
                reasons.append(f"Precision and recall are closely aligned (gap = {gap:.4f}).")
            else:
                reasons.append(f"Precision and recall diverge by {gap:.4f}, suggesting class-level trade-offs or class imbalance.")

        if comparison_info is not None and selected_run is not None:
            recs = _build_non_redundant_classification_recommendations(selected_run, comparison_info)
        else:
            sweep_param = "n_estimators" if "Random Forest" in model_name else "C"
            alt_model = "Logistic Regression" if "Random Forest" in model_name else "Random Forest"
            recs = [
                NextExperimentRecommendation(
                    title=f"Run Comparable {alt_model} Baseline",
                    what_to_change=f"Train and evaluate {alt_model}",
                    what_to_keep_constant=f"Same dataset, target column, test split ({test_size}), and random seed ({random_state})",
                    what_to_measure="Accuracy, weighted F1-score, precision, and recall",
                    why_useful=f"Provides a controlled baseline comparison against {model_name}.",
                    expected_support_or_weakening=f"Comparing directly against {acc_pct} resolves whether Random Forest outperforms Logistic Regression.",
                    can_run_predefined=True,
                    recommended_runner_config={
                        "experiment_type": "Classification",
                        "model_choice": alt_model,
                    },
                ),
                NextExperimentRecommendation(
                    title=f"{model_name} Hyperparameter Sweep ({sweep_param})",
                    what_to_change=f"Sweep {sweep_param} across predefined values",
                    what_to_keep_constant=f"Test split ({test_size}) and random seed ({random_state})",
                    what_to_measure="Weighted F1-score across sweep steps",
                    why_useful=f"Checks sensitivity of {model_name} to {sweep_param}.",
                    expected_support_or_weakening=f"Higher F1 than {f1_str} supports tuning {sweep_param}.",
                    can_run_predefined=True,
                    recommended_runner_config={
                        "experiment_type": "Parameter Sweep",
                        "model_choice": model_name,
                        "sweep_param": sweep_param,
                    },
                ),
            ]

    elif exp_type == "regression":
        mae = metrics.get("mae")
        rmse = metrics.get("rmse")
        r2 = metrics.get("r2_score")

        if isinstance(r2, (int, float)):
            if r2 >= 0.60:
                status = "Supported"
                fit_desc = "strong"
            elif r2 >= 0.25:
                status = "Inconclusive"
                fit_desc = "moderate"
            else:
                status = "Not Supported"
                fit_desc = "weak"
            r2_str = f"{r2:.4f}"
            var_pct = f"{max(0.0, r2) * 100:.1f}%"
        else:
            status = "Inconclusive"
            fit_desc = "unverified"
            r2_str = "N/A"
            var_pct = "N/A"

        mae_str = f"{mae:.4f}" if isinstance(mae, (int, float)) else "N/A"
        rmse_str = f"{rmse:.4f}" if isinstance(rmse, (int, float)) else "N/A"

        summary = (
            f"The {model_name} regressor achieved MAE = {mae_str}, RMSE = {rmse_str}, "
            f"and R² = {r2_str}{split_note}."
        )
        if isinstance(r2, (int, float)) and r2 < 0:
            what_suggests = (
                f"A negative R² ({r2_str}) indicates that predictions underperformed a constant mean-value baseline on this test split."
            )
        else:
            what_suggests = (
                f"An R² of {r2_str} indicates {fit_desc} explanatory fit, accounting for {var_pct} of target variance on the test split."
            )

        reasons = [
            f"Error metrics (MAE = {mae_str}, RMSE = {rmse_str}) reflect out-of-sample residuals after numeric scaling and imputation."
        ]
        if isinstance(mae, (int, float)) and isinstance(rmse, (int, float)) and mae > 0:
            ratio = rmse / mae
            if ratio > 1.35:
                reasons.append(f"RMSE/MAE ratio ({ratio:.2f}) indicates that larger error outliers are increasing squared error.")
            else:
                reasons.append(f"RMSE/MAE ratio ({ratio:.2f}) suggests relatively uniform residual errors across test samples.")

        alt_model = "Linear Regression" if "Random Forest" in model_name else "Random Forest Regressor"
        recs = [
            NextExperimentRecommendation(
                title="Tree Depth Parameter Sweep" if "Random Forest" in model_name else f"Model Comparison vs {alt_model}",
                what_to_change="Sweep max_depth across [2, 4, 6, 8, 12, 16]" if "Random Forest" in model_name else f"Switch regressor to {alt_model}",
                what_to_keep_constant=f"Dataset, target column, test split ({test_size}), and random seed ({random_state})",
                what_to_measure="Test R², RMSE, and MAE",
                why_useful="Tests whether controlling tree depth or model nonlinearity improves out-of-sample error.",
                expected_support_or_weakening=f"Lower RMSE than {rmse_str} and higher R² than {r2_str} supports the alternative configuration.",
                can_run_predefined=True,
                recommended_runner_config={
                    "experiment_type": "Parameter Sweep" if "Random Forest" in model_name else "Regression",
                    "model_choice": "Random Forest Regressor" if "Random Forest" in model_name else alt_model,
                },
            )
        ]

    elif exp_type == "clustering":
        k = metrics.get("n_clusters", config.get("n_clusters"))
        inertia = metrics.get("inertia")
        sil = metrics.get("silhouette_score")
        pca_var = metrics.get("pca_explained_variance_ratio")

        if isinstance(sil, (int, float)):
            if sil >= 0.50:
                status = "Supported"
                sep_desc = "well-separated"
            elif sil >= 0.25:
                status = "Inconclusive"
                sep_desc = "moderately overlapping"
            else:
                status = "Not Supported"
                sep_desc = "weakly separated"
            sil_str = f"{sil:.4f}"
        else:
            status = "Inconclusive"
            sep_desc = "unverified"
            sil_str = "N/A"

        pca_note = (
            f" The 2D PCA projection retains {sum(pca_var) * 100:.1f}% of total feature variance."
            if isinstance(pca_var, list) and pca_var
            else ""
        )
        summary = (
            f"K-Means clustering (k = {k}) produced inertia = {inertia} and silhouette score = {sil_str}.{pca_note}"
        )
        what_suggests = (
            f"A silhouette score of {sil_str} suggests {sep_desc} clusters in standardized feature space."
        )
        reasons = [
            f"Cluster assignments were computed on standardized numeric features with k = {k} and random seed {config.get('random_state', 42)}."
        ]
        recs = [
            NextExperimentRecommendation(
                title="Cluster Count (k) Sensitivity Check",
                what_to_change="Vary number of clusters k (e.g., k = 2, 3, 4, 5)",
                what_to_keep_constant=f"Same dataset, standardized numeric features, and random seed ({config.get('random_state', 42)})",
                what_to_measure="Silhouette score and inertia across k values",
                why_useful="Compares cluster cohesion and separation across candidate cluster counts.",
                expected_support_or_weakening=f"Higher silhouette score than {sil_str} indicates a cleaner natural grouping.",
                can_run_predefined=True,
                recommended_runner_config={"experiment_type": "Clustering"},
            )
        ]

    else:
        swept_model = config.get("model_type", model_name)
        param_name = config.get("param_name", "parameter")
        param_values = config.get("param_values", [])
        steps = metrics.get("sweep_steps", len(param_values) if isinstance(param_values, list) else "N/A")

        status = "Inconclusive"
        summary = (
            f"Parameter sweep on {swept_model} evaluated {steps} configurations of '{param_name}' "
            f"({param_values}){split_note}."
        )
        what_suggests = (
            f"The sweep curve visualizes how varying '{param_name}' changes test performance under a fixed data split."
        )
        reasons = [
            f"All {steps} sweep runs held the train/test split and random seed ({random_state}) constant while varying '{param_name}'."
        ]
        recs = [
            NextExperimentRecommendation(
                title=f"Evaluate Best {swept_model} Configuration",
                what_to_change=f"Run a standalone experiment comparing {swept_model} against a baseline model",
                what_to_keep_constant=f"Test split ({test_size}) and random seed ({random_state})",
                what_to_measure="Full metric suite and confusion matrix or residual plot",
                why_useful="Inspects per-class or residual behavior for the best parameter from the sweep.",
                expected_support_or_weakening="Consistent improvements across precision/recall or RMSE/R² strengthen empirical support.",
                can_run_predefined=True,
            )
        ]

    interp = InterpretationResult(
        summary=summary,
        what_results_suggest=what_suggests,
        hypothesis_status=status,
        possible_reasons=reasons,
        limitations=[
            "Rule-based fallback summary: derived deterministically from recorded run metrics without LLM domain synthesis.",
            "Metrics reflect a single train/test partition without nested cross-validation or external test validation.",
            "Statistical fit or correlation does not establish causal mechanisms.",
        ],
    )
    return interp, recs


def build_rule_based_analysis(
    run_record: Dict[str, Any],
    fallback_reason: str = "api_key_missing",
    retry_after: Optional[str] = None,
    quota_message: Optional[str] = None,
    comparison_info: Optional[Dict[str, Any]] = None,
    require_comparative: bool = False,
) -> Dict[str, Any]:
    """Builds a labeled deterministic rule-based analysis package (comparative when available)."""
    exp_type = run_record["experiment_type"]
    config = run_record["config"]
    metrics = run_record["metrics"]
    model_name = config.get("model_type", run_record.get("model_name", exp_type.title()))

    if comparison_info and comparison_info.get("comparison_available"):
        interp, recs = _build_comparative_rule_based_parts(run_record, comparison_info)
        analysis_mode = "comparative_rule_based"
    else:
        interp, recs = _build_single_run_rule_based_parts(
            exp_type,
            model_name,
            config,
            metrics,
            selected_run=run_record,
            comparison_info=comparison_info,
            require_comparative=require_comparative,
        )
        analysis_mode = "single_rule_based"

    interp_dict = interp.model_dump()
    interp_dict["source"] = "rule_based"
    interp_dict["source_label"] = RULE_BASED_LABEL
    interp_dict["analysis_mode"] = analysis_mode
    interp_dict["fallback_reason"] = fallback_reason
    if retry_after:
        interp_dict["retry_after"] = retry_after
    if comparison_info is not None:
        interp_dict["comparison"] = comparison_info

    return {
        "interpretation": interp_dict,
        "recommendations": [r.model_dump() for r in recs],
        "comparison": comparison_info,
        "source": "rule_based",
        "source_label": RULE_BASED_LABEL,
        "analysis_mode": analysis_mode,
        "quota_exhausted": fallback_reason == "quota_exhausted",
        "ollama_unavailable": fallback_reason == "ollama_unavailable",
        "quota_message": quota_message,
        "provider_error": quota_message if fallback_reason == "ollama_unavailable" else None,
        "retry_after": retry_after,
    }


def _format_comparison_context_for_llm(comparison_info: Dict[str, Any]) -> str:
    """Formats verified comparative metrics and completed comparisons as factual prompt context."""
    lines: List[str] = []
    if comparison_info.get("comparison_available"):
        lines.append(
            f"Comparable runs found: Random Forest (Run #{comparison_info.get('rf_run_id')}) vs "
            f"Logistic Regression (Run #{comparison_info.get('lr_run_id')})."
        )
        lines.append(f"Rule-verified comparative hypothesis status: {comparison_info.get('hypothesis_status')}")
        for row in comparison_info.get("metrics_table", []):
            lines.append(
                f"- {row['metric']}: RF={row['random_forest']} ({row['rf_pct']}%), "
                f"LR={row['logistic_regression']} ({row['lr_pct']}%), "
                f"signed diff={row['signed_diff_pp']:+.2f} pp, abs diff={row['abs_diff_pp']:.2f} pp"
            )
        cls_comp = comparison_info.get("class_level_comparison") or {}
        if cls_comp.get("available"):
            for crow in cls_comp.get("per_class_rows", []):
                lines.append(
                    f"- Class {crow['class']}: RF (P={crow['rf_precision']}, R={crow['rf_recall']}, F1={crow['rf_f1']}) vs "
                    f"LR (P={crow['lr_precision']}, R={crow['lr_recall']}, F1={crow['lr_f1']})"
                )
        else:
            lines.append(f"- Class-level note: {cls_comp.get('note')}")
    else:
        lines.append(f"Comparison status: {comparison_info.get('comparison_status')} — {comparison_info.get('reason')}")

    completed = comparison_info.get("completed_comparisons") or []
    if completed:
        lines.append("Already completed comparisons/sweeps (DO NOT recommend repeating): " + "; ".join(completed))

    return "\n".join(lines)


def analyze_and_interpret_run(
    workspace: Dict[str, Any],
    run_record: Dict[str, Any],
    plan_dict: Optional[Dict[str, Any]] = None,
    workspace_runs: Optional[List[Dict[str, Any]]] = None,
    selected_metrics: Optional[List[str]] = None,
    provider: Optional[str] = None,
    model: Optional[str] = None,
) -> Dict[str, Any]:
    """
    Generates comparative scientific interpretation and non-redundant recommendations across
    comparable runs using the configured provider (Ollama default, Gemini optional),
    falling back gracefully to rule-based analysis when unavailable.
    """
    ws_id = workspace["id"]
    rq = workspace["research_question"]
    hyp = workspace.get("hypothesis", "")

    exp_type = run_record["experiment_type"]
    config = run_record["config"]
    metrics = run_record["metrics"]
    model_name = config.get("model_type", run_record.get("model_name", "Model"))

    # Discover comparable runs in the active workspace
    if workspace_runs is None:
        workspace_runs = list_experiment_runs(ws_id)

    comparison_info = (
        build_comparative_analysis(run_record, workspace_runs=workspace_runs, selected_metrics=selected_metrics)
        if exp_type == "classification"
        else None
    )

    require_comparative = _is_comparative_hypothesis(workspace)
    chosen_provider = get_active_provider_name(provider)

    if chosen_provider == "gemini":
        configured, status_msg = is_gemini_configured()
        if not configured:
            return build_rule_based_analysis(
                run_record,
                fallback_reason="api_key_missing",
                comparison_info=comparison_info,
                require_comparative=require_comparative,
            )
    else:
        configured, status_msg = is_llm_configured(provider="ollama", model=model)
        if not configured:
            return build_rule_based_analysis(
                run_record,
                fallback_reason="ollama_unavailable",
                quota_message=status_msg,
                comparison_info=comparison_info,
                require_comparative=require_comparative,
            )

    comp_context = _format_comparison_context_for_llm(comparison_info) if comparison_info else ""

    try:
        interp = interpret_results_llm(
            research_question=rq,
            hypothesis=hyp,
            experiment_type=exp_type,
            model_name=model_name,
            config=config,
            metrics=metrics,
            plan_context=str(plan_dict.get("objective") if plan_dict else ""),
            comparison_context=comp_context,
            provider=chosen_provider,
            model=model,
        )
    except GeminiQuotaExhaustedError as qe:
        return build_rule_based_analysis(
            run_record,
            fallback_reason="quota_exhausted",
            retry_after=qe.retry_after,
            quota_message=str(qe),
            comparison_info=comparison_info,
            require_comparative=require_comparative,
        )
    except (OllamaUnavailableError, OllamaModelNotFoundError) as oe:
        return build_rule_based_analysis(
            run_record,
            fallback_reason="ollama_unavailable",
            quota_message=str(oe),
            comparison_info=comparison_info,
            require_comparative=require_comparative,
        )

    is_comparative = bool(comparison_info and comparison_info.get("comparison_available"))
    if chosen_provider == "gemini":
        source_key = "gemini"
        source_label = GEMINI_LABEL
        analysis_mode = "comparative_gemini" if is_comparative else "single_gemini"
    else:
        active_ollama_model = get_active_ollama_model(model)
        source_key = "ollama"
        source_label = f"{OLLAMA_LABEL} ({active_ollama_model})"
        analysis_mode = "comparative_ollama" if is_comparative else "single_ollama"

    interp_dict = interp.model_dump()
    interp_dict["source"] = source_key
    interp_dict["source_label"] = source_label
    interp_dict["analysis_mode"] = analysis_mode
    if chosen_provider == "ollama":
        interp_dict["llm_model"] = get_active_ollama_model(model)
    if comparison_info is not None:
        interp_dict["comparison"] = comparison_info

    evidence_chunks = retrieve_relevant_chunks(ws_id, query=rq, top_k=3)
    ev_text = "\n".join([f"[{c.source_filename} p.{c.page_number}]: {c.content}" for c in evidence_chunks])

    fallback_recs = (
        _build_non_redundant_classification_recommendations(run_record, comparison_info)
        if comparison_info is not None
        else _build_single_run_rule_based_parts(exp_type, model_name, config, metrics)[1]
    )

    try:
        llm_recs = recommend_next_experiments_llm(
            research_question=rq,
            hypothesis=hyp,
            current_model=model_name,
            current_metrics=metrics,
            interpretation_summary=interp.summary,
            evidence_context=ev_text,
            comparison_context=comp_context,
            provider=chosen_provider,
            model=model,
        )
        final_recs = (
            _filter_redundant_llm_recommendations(llm_recs, comparison_info, fallback_recs)
            if comparison_info is not None
            else llm_recs
        )
        return {
            "interpretation": interp_dict,
            "recommendations": [r.model_dump() for r in final_recs],
            "comparison": comparison_info,
            "source": source_key,
            "source_label": source_label,
            "analysis_mode": analysis_mode,
            "quota_exhausted": False,
            "ollama_unavailable": False,
            "quota_message": None,
            "provider_error": None,
            "retry_after": None,
        }
    except GeminiQuotaExhaustedError as qe:
        return {
            "interpretation": interp_dict,
            "recommendations": [r.model_dump() for r in fallback_recs],
            "comparison": comparison_info,
            "source": "gemini_partial",
            "source_label": source_label,
            "analysis_mode": analysis_mode,
            "quota_exhausted": True,
            "ollama_unavailable": False,
            "quota_message": str(qe),
            "provider_error": None,
            "retry_after": qe.retry_after,
        }
    except (OllamaUnavailableError, OllamaModelNotFoundError) as oe:
        return {
            "interpretation": interp_dict,
            "recommendations": [r.model_dump() for r in fallback_recs],
            "comparison": comparison_info,
            "source": "ollama_partial",
            "source_label": source_label,
            "analysis_mode": analysis_mode,
            "quota_exhausted": False,
            "ollama_unavailable": True,
            "quota_message": str(oe),
            "provider_error": str(oe),
            "retry_after": None,
        }
